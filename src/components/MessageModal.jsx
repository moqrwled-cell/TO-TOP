export default function MessageModal() {
  const [isOpen, setIsOpen] = useState(false);
  const [message, setMessage] = useState('');

  useEffect(() => {
    // Check local storage for last message time
    const lastTime = localStorage.getItem('totop_last_message_time');
    const now = new Date().getTime();
    
    // 4 hours in milliseconds = 4 * 60 * 60 * 1000 = 14400000
    const FOUR_HOURS = 14400000;
    
    if (!lastTime || (now - parseInt(lastTime, 10)) > FOUR_HOURS) {
      // Time to show a message
      const randomMsg = MESSAGES_DB[Math.floor(Math.random() * MESSAGES_DB.length)];
      setMessage(randomMsg);
      setIsOpen(true);
      
      localStorage.setItem('totop_last_message_time', now.toString());
    }
  }, []);

  if (!isOpen) return null;

  return (
    <div style={{
      position: 'fixed',
      top: 0, left: 0, right: 0, bottom: 0,
      background: 'rgba(0,0,0,0.8)',
      backdropFilter: 'blur(10px)',
      display: 'flex',
      alignItems: 'center',
      justifyContent: 'center',
      zIndex: 9999999,
      padding: '2rem'
    }}>
      <div className="glass-panel animate-fade-up" style={{
        maxWidth: '500px',
        width: '100%',
        padding: '3rem 2rem',
        textAlign: 'center',
        position: 'relative',
        background: 'var(--surface-color)',
        border: '1px solid var(--surface-border)',
        boxShadow: '0 20px 50px rgba(0,0,0,0.2), inset 0 0 0 1px var(--surface-border)'
      }}>
        <button 
          onClick={() => setIsOpen(false)}
          style={{ position: 'absolute', top: '15px', right: '15px', background: 'transparent', border: 'none', color: 'var(--text-secondary)', cursor: 'pointer' }}
        >
          <X size={24} />
        </button>
        
        <div style={{
          width: '70px', height: '70px', borderRadius: '50%',
          background: 'var(--surface-border)',
          display: 'flex', alignItems: 'center', justifyContent: 'center',
          margin: '0 auto 2rem',
          boxShadow: '0 0 20px var(--surface-border)'
        }}>
          <MailOpen size={36} color="var(--text-primary)" />
        </div>
        
        <h2 style={{ fontSize: '1.5rem', marginBottom: '1.5rem', color: '#ffd700' }}>رسالة لك 💌</h2>
        
        <p style={{ 
          fontSize: '1.25rem', 
          lineHeight: '2', 
          whiteSpace: 'pre-line',
          color: 'var(--text-primary)',
          fontFamily: 'var(--font-quote)',
          textShadow: '0 2px 10px rgba(128,128,128,0.2)'
        }}>
          {message}
        </p>

        <button 
          onClick={() => setIsOpen(false)}
          className="btn-premium"
          style={{ marginTop: '3rem', width: '100%', justifyContent: 'center', padding: '1rem' }}
        >
          أكمل يومك بكل طاقة
        </button>
      </div>
    </div>
  );
}
